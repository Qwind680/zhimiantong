/* 扁平化索引 + 工具 */
const EXAM_INDEX = (() => {
  const list = [];
  CATS.forEach(c => {
    (EXAM[c.key] || []).forEach((q, i) => {
      list.push(Object.assign({ id: c.key + '-' + (i + 1), cat: c.key, catLabel: c.label, no: i + 1 }, q));
    });
  });
  return list;
})();

const EXAM_BY_ID = Object.fromEntries(EXAM_INDEX.map(q => [q.id, q]));
const EXAM_CAT_COUNT = Object.fromEntries(
  CATS.map(c => [c.key, (EXAM[c.key] || []).length])
);
const EXAM_TOTAL = EXAM_INDEX.length;

/* 把答案转成可读文本 */
function EXAM_ANSWER_TEXT(q) {
  if (q.t === 'single') return `第 ${String.fromCharCode(65 + q.a)} 项`;
  if (q.t === 'multi')  return q.a.map(i => String.fromCharCode(65 + i)).join('、') + `（共 ${q.a.length} 项）`;
  if (q.t === 'judge')  return q.a ? '正确' : '错误';
  return '';
}
function EXAM_OPTION_LETTER(i) { return String.fromCharCode(65 + i); }


/* ==================== 页面交互（原 bank.js） ==================== */

/* ============================================================
   职面通 · 题库交互
   ------------------------------------------------------------
   · 左侧一级分类：分类 / 收藏
   · 「分类」下按职位类型分二级
   · 题目默认只显示题干，点开才出答案
   · 收藏存 localStorage，切分类/刷新都还在
   ============================================================ */
(() => {
  'use strict';

  const $  = (s, r = document) => r.querySelector(s);
  const $$ = (s, r = document) => Array.from(r.querySelectorAll(s));
  const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

  const FAV_KEY = 'zt-bank-fav';
  const OPEN_KEY = 'zt-bank-open';

  const read = (k, d) => { try { return JSON.parse(localStorage.getItem(k)) || d; } catch (_) { return d; } };
  const write = (k, v) => { try { localStorage.setItem(k, JSON.stringify(v)); } catch (_) {} };

  let favs = new Set(read(FAV_KEY, []));
  const openSet = new Set(read(OPEN_KEY, []));
  let view = { kind: 'cat', cat: 'tech', ftype: 'all', q: '' };

  /* ---------- 侧栏 ---------- */
  function renderSide() {
    $('#bk-cats').innerHTML = CATS.map(c => `
      <button type="button" class="bk-nav__item bk-nav__link ${view.kind === 'cat' && view.cat === c.key ? 'is-on' : ''}"
              data-cat="${c.key}" title="${esc(c.sub)}">
        <span>${esc(c.label)}</span>
        <span class="bk-nav__n">${EXAM_CAT_COUNT[c.key]}</span>
      </button>`).join('');

    const favList = EXAM_INDEX.filter(q => favs.has(q.id));
    const head = `
      <button type="button" class="bk-nav__link ${view.kind === 'fav' ? 'is-on' : ''} ${favList.length ? '' : 'is-empty'}"
              data-view="fav">
        <span>我的收藏</span>
        <span class="bk-nav__n">${favList.length}</span>
      </button>`;

    const body = favList.length
      ? `<div class="bk-fav">${favList.map(q => `
          <button type="button" class="bk-fav__item" data-jump="${q.id}">
            <span class="bk-fav__t">${hl(q.s, view.q)}</span>
            <span class="bk-fav__c">${esc(q.catLabel)}</span>
          </button>`).join('')}</div>`
      : `<p class="bk-fav__empty">还没收藏。<br>点题目右边的 ☆ 就能收进来。</p>`;

    $('#bk-fav').innerHTML = head + body;
  }

  /* ---------- 列表 ---------- */
  function current() {
    // 有关键词时全库搜——用户搜的是「东西」，并不知道它在哪个分类下。
    // 在「收藏」视图里搜则只搜收藏。
    let list = view.kind === 'fav'
      ? EXAM_INDEX.filter(q => favs.has(q.id))
      : EXAM_INDEX.slice();
    if (!view.q && view.kind === 'cat') list = list.filter(q => q.cat === view.cat);
    if (view.ftype !== 'all') list = list.filter(q => q.t === view.ftype);
    if (view.q) {
      const k = view.q.toLowerCase();
      list = list.filter(q =>
        q.s.toLowerCase().includes(k) ||
        (q.o || []).some(o => o.toLowerCase().includes(k)) ||
        (q.a && typeof q.a === 'string' && q.a.toLowerCase().includes(k)) ||
        q.catLabel.includes(view.q)
      );
    }
    return list;
  }

  function hl(text, kw) {
    if (!kw) return esc(text);
    const safe = esc(text);
    const k = kw.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    return safe.replace(new RegExp(k, 'gi'), m => `<mark>${m}</mark>`);
  }

  function renderList() {
    const list = current();
    const total = EXAM_TOTAL;

    const titleMap = {
      cat: null,
      fav: ['我的收藏', favs.size ? `收藏了 ${favs.size} 题，它们跨职位类型。` : '还没有收藏的题目。点题目右边的 ☆ 就能收进来。'],
    };

    if (view.kind === 'cat') {
      const c = CATS.find(x => x.key === view.cat);
      titleMap.cat = [c.label, `${c.sub} · 共 ${EXAM_CAT_COUNT[c.key]} 题。点开题目看答案。`];
    }
    const [title, sub] = titleMap[view.kind];
    $('#bk-title').textContent = title;
    $('#bk-sub').textContent = sub;

    const scope = view.q
      ? (view.kind === 'fav' ? '在收藏中搜索' : '全库搜索')
      : (view.kind === 'fav' ? '我的收藏' : (view.cat === 'all' ? '全部职位类型' : CATS.find(c => c.key === view.cat).label));
    $('#bk-count').innerHTML = `${scope} · <b>${list.length}</b> 题` +
      (view.q ? `（关键词「${esc(view.q)}」）` : '') +
      (view.ftype !== 'all' ? ` · 题型「${QTYPE[view.ftype].label}」` : '');

    $('#bk-empty').hidden = list.length > 0;
    $('#bk-list').innerHTML = list.map(qCard).join('');
  }

  function qCard(q) {
    const open = openSet.has(q.id);
    const fav = favs.has(q.id);

    const head = `
      <div class="bk-q__head">
        <button type="button" class="bk-q__toggle" data-toggle="${q.id}"
                aria-expanded="${open}" aria-controls="pnl-${q.id}">
          <span class="bk-q__no">${String(q.no).padStart(2, '0')}</span>
          <span class="bk-q__body">
            <span class="bk-q__meta">
              <span class="bk-q__type" data-t="${q.t}">${QTYPE[q.t].abbr}</span>
              <span class="bk-q__cat">${esc(q.catLabel)}</span>
            </span>
            <span class="bk-q__stem">${hl(q.s, view.q)}</span>
          </span>
        </button>
        <span class="bk-q__ops">
          <button type="button" class="bk-favbtn ${fav ? 'is-on' : ''}" data-favbtn="${q.id}"
                  aria-pressed="${fav}" aria-label="${fav ? '取消收藏' : '收藏这道题'}" title="${fav ? '取消收藏' : '收藏'}">
            <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linejoin="round" aria-hidden="true">
              <path d="m12 3.6 2.6 5.3 5.9.9-4.25 4.15 1 5.85L12 17.05 6.75 19.8l1-5.85L3.5 9.8l5.9-.9L12 3.6Z"/>
            </svg>
          </button>
          <span class="bk-q__caret" aria-hidden="true">
            <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">
              <path d="m6 9 6 6 6-6"/>
            </svg>
          </span>
        </span>
      </div>`;

    // 答案不预先生成——没点开的题，DOM 里连一个字都不该有
    const panel = open ? `
      <div class="bk-q__panel" id="pnl-${q.id}">
        ${qPanelInner(q)}
        <div class="bk-q__foot">
          <span class="bk-q__src">${esc(q.catLabel)} · 第 ${q.no} 题</span>
          <button type="button" class="bk-q__fold" data-toggle="${q.id}">收起</button>
        </div>
      </div>` : '';

    return `<li class="bk-q ${open ? 'is-open' : ''} ${fav ? 'is-fav' : ''}" data-id="${q.id}">${head}${panel}</li>`;
  }

  function qPanelInner(q) {
    let out = '';
    if (q.t === 'single' || q.t === 'multi') {
      out += `<div class="bk-opts">${(q.o || []).map((o, i) => {
        const right = q.t === 'single' ? i === q.a : q.a.includes(i);
        return `<div class="bk-opt ${right ? 'is-right' : ''}">
          <span class="bk-opt__k">${EXAM_OPTION_LETTER(i)}</span>
          <span>${hl(o, view.q)}</span>
        </div>`;
      }).join('')}</div>`;
    }
    let val;
    if (q.t === 'judge')      val = `<span class="bk-ans__v bk-ans__v--tf ${q.a ? '' : 'is-no'}">${q.a ? '正确 ✓' : '错误 ✗'}</span>`;
    else if (q.t === 'short') val = `<span class="bk-ans__v">${esc(q.a)}</span>`;
    else                      val = `<span class="bk-ans__v">${esc(EXAM_ANSWER_TEXT(q))}</span>`;
    out += `<div class="bk-ans">
      <p class="bk-ans__l">参考答案</p>
      ${val}
      ${q.e ? `<div class="bk-ans__e"><b>解析</b>${esc(q.e)}</div>` : ''}
    </div>`;
    return out;
  }

  /* ---------- 事件 ---------- */
  document.addEventListener('click', (e) => {
    // 收藏
    const favBtn = e.target.closest('[data-favbtn]');
    if (favBtn) {
      e.preventDefault(); e.stopPropagation();
      const id = favBtn.dataset.favbtn;
      if (favs.has(id)) { favs.delete(id); } else { favs.add(id); }
      write(FAV_KEY, [...favs]);
      if (favs.has(id)) { const el = $(`.bk-q[data-id="${id}"] .bk-favbtn`); if (el) el.classList.add('pop'); }
      renderSide(); renderList();
      return;
    }
    // 展开/收起
    const tog = e.target.closest('[data-toggle]');
    if (tog) {
      const id = tog.dataset.toggle;
      if (openSet.has(id)) openSet.delete(id); else openSet.add(id);
      write(OPEN_KEY, [...openSet]);
      renderList();
      return;
    }
    // 切分类
    const cat = e.target.closest('[data-cat]');
    if (cat) { view = { ...view, kind: 'cat', cat: cat.dataset.cat }; closeSide(); renderSide(); renderList(); return; }
    if (e.target.closest('[data-view="fav"]')) { view = { ...view, kind: 'fav' }; closeSide(); renderSide(); renderList(); return; }
    // 侧栏里点收藏项 → 跳过去并展开
    const jump = e.target.closest('[data-jump]');
    if (jump) {
      const id = jump.dataset.jump;
      const q = EXAM_BY_ID[id];
      if (q) { view = { ...view, kind: 'cat', cat: q.cat }; openSet.add(id); write(OPEN_KEY, [...openSet]); }
      closeSide(); renderSide(); renderList();
      const el = $(`.bk-q[data-id="${id}"]`);
      if (el) el.scrollIntoView({ behavior: 'smooth', block: 'center' });
      return;
    }
    // 题型筛选
    const chip = e.target.closest('[data-ftype]');
    if (chip) {
      view.ftype = chip.dataset.ftype;
      $$('.bk-chip').forEach(c => c.classList.toggle('is-on', c === chip));
      renderList();
      return;
    }
  });

  // 搜索
  const qInput = $('#bk-q');
  qInput.addEventListener('input', () => {
    view.q = qInput.value.trim();
    $('#bk-clear').hidden = !view.q;
    renderSide(); renderList();
  });
  $('#bk-clear').addEventListener('click', () => {
    qInput.value = ''; view.q = ''; $('#bk-clear').hidden = true;
    renderSide(); renderList(); qInput.focus();
  });

  /* ---------- 移动端抽屉 ---------- */
  const side = $('#bk-side'), scrim = $('#bk-scrim'), sideBtn = $('#bk-sidebtn');
  const openSide  = () => { side.classList.add('is-open'); scrim.hidden = false; sideBtn.setAttribute('aria-expanded', 'true'); };
  const closeSide = () => { side.classList.remove('is-open'); scrim.hidden = true; sideBtn.setAttribute('aria-expanded', 'false'); };
  sideBtn.addEventListener('click', () => side.classList.contains('is-open') ? closeSide() : openSide());
  scrim.addEventListener('click', closeSide);
  $('#bk-close').addEventListener('click', closeSide);
  addEventListener('keydown', e => { if (e.key === 'Escape') closeSide(); });

  renderSide();
  renderList();
})();
